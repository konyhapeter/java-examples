CREATE TABLE aircraft (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration VARCHAR(20) NOT NULL UNIQUE,
    model VARCHAR(100) NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    status VARCHAR(20) NOT NULL
);

CREATE TABLE passengers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    passport_number VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE flights (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    flight_number VARCHAR(12) NOT NULL UNIQUE,
    origin VARCHAR(100) NOT NULL,
    destination VARCHAR(100) NOT NULL,
    departure_time TIMESTAMP NOT NULL,
    arrival_time TIMESTAMP NOT NULL,
    status VARCHAR(20) NOT NULL,
    aircraft_id BIGINT NOT NULL REFERENCES aircraft(id)
);

CREATE INDEX idx_flights_aircraft_schedule ON flights (aircraft_id, departure_time, arrival_time);

CREATE TABLE bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    passenger_id BIGINT NOT NULL REFERENCES passengers(id),
    flight_id BIGINT NOT NULL REFERENCES flights(id),
    seat_number VARCHAR(8) NOT NULL,
    status VARCHAR(20) NOT NULL
);

CREATE INDEX idx_bookings_flight_status ON bookings (flight_id, status);
CREATE INDEX idx_bookings_passenger_flight_status ON bookings (passenger_id, flight_id, status);
